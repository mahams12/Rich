export function projectSortTime(project: Project) {
  const raw = project.publishedAt || project.createdAt;
  if (!raw) return 0;
  const time = Date.parse(raw);
  return Number.isNaN(time) ? 0 : time;
}

export function sortProjectsNewestFirst(list: Project[]) {
  return [...list].sort((a, b) => {
    const diff = projectSortTime(b) - projectSortTime(a);
    if (diff !== 0) return diff;
    return b.id.localeCompare(a.id);
  });
}

export function getPublishedProjects(list: Project[] = projects) {
  return sortProjectsNewestFirst(list.filter((project) => project.status === "published"));
}

export function getProjectBySlug(slug: string, list: Project[] = projects) {
  return list.find((project) => project.slug === slug);
}

export function relatedProjects(slug: string, list: Project[] = projects) {
  const current = getProjectBySlug(slug, list);
  if (!current) return list.slice(0, 4);
  return list
    .filter((project) => project.slug !== slug && project.category === current.category)
    .slice(0, 3)
    .concat(list.filter((project) => project.slug !== slug && project.featured).slice(0, 2))
    .filter((project, index, arr) => arr.findIndex((item) => item.id === project.id) === index)
    .slice(0, 4);
}
